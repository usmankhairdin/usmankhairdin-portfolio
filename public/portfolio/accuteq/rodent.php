                              <p>The range in body size between the mouse,18 grams 0.64-ounce, body 12 cm ,4.7 inches long, and the marmot, 3,000 grams, body 50 cm long, spans the majority of living rodents, but the extremes are remarkable. One of the smallest is Delany’s swamp mouse associated with bamboo in the marshes and mountain forests in Africa. It weighs 5 to 7 grams, and the body is 5 to 6 cm long. The largest is the capybara of Central and South America, which weighs 35 to 66 kg ,77 to 146 pounds and stands 50 to 60 cm at the shoulder, with a body 100 to 135 cm long. Some extinct species were even larger, attaining the size of a black bear or small rhinoceros. The largest rodent ever recorded, lived some two to four million years ago, during the Pleistocene and Pliocene epochs; by some estimates it grew to a length of about 3 metres about 10 feet and weighed nearly 1000 kgs.</p>
