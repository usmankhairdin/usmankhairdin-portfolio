                              <p>Rodents may be diurnal, nocturnal, or sometimes active part of the day and night. Although some species are herbivorous, diets of most include vegetable and animal matter. Others are opportunistic generalists, and some are specialized predators, not only of arthropods but sometimes of vertebrates. Food is either eaten where gathered or carried to burrows and stored. Species living in arid habitats and on oceanic islands are able to obtain their water requirements from their food. A wide variety of shelters are used or constructed; these range from tree holes, rock crevices, or simple burrows to hidden nests on the forest floor, leaf and stick structures in tree crowns, mounds of cut vegetation built in aquatic environments or complex networks of tunnels and galleries. Rodents may be active all year or enter periods of dormancy or deep hibernation. Breeding time and frequency, length of gestation, and litter size vary widely, but two of the mostprolific are both associated with humans. The brown rat can give birth to litters of up to 22 offspring, and thehouse mouse can produce up to 14 litters annually. Population size may remain stable or fluctuate, and some species, most notably lemmings, migrate when populations become excessively large.</p>
