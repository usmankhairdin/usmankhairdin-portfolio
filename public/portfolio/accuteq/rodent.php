                            <p>The specialized body forms of other kinds of rodents tie them closer to particular locomotor patterns and ecologies. Some strictly arboreal species have a prehensile tail; others glide from tree to tree supported by fur-covered membranes between appendages. Highly specialized fossorial rodents, including blind mole rats, blesmols, and ground squirrels, are cylindrical and furry with protruding, strong incisors, small eyes and ears, and large forefeet bearing powerful digging claws. Semiaquatic rodents such as beavers, muskrats, nutrias, and water rats, possess specialized traits allowing them to forage in aquatic habitats yet den in ground burrows. Terrestrial leaping species, such as kangaroos, rats, jumping mice, gerbils, and jerboas, have short forelimbs, long and powerful hind limbs and feet, and a long tail used for balance. Body forms of some rodents converge on those in nonrodent orders, resembling pigs or deer. There is also convergence between distantly related groups of rodents in particular body forms and associated natural histories.Regardless of body form, all rodents share the same basic tools.</p>
