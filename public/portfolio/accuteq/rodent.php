                              <p>Rodents have lived on the planet for at least 56 million years and modern humans for less than one million, but the consequences of their interactions during that short overlap of evolutionary time have been profound. For rodents, early humans were just another predator to avoid, but with Homo Sapiens transition from nomadic hunting and gathering to sedentary agricultural practices, humans became a reliable source of shelter and food for those species having the innate genetic and behavioural abilities to adapt to man-made habitats. The impact of these species upon human populations ranges from inconvenient to deadly. Crops are damaged before harvest; stored food is contaminated by rodent waste; water-impounding structures leak from burrowing; and objects are damaged by gnawing. Certain species are reservoirs for diseases such as plague, murine, typhus, scrub typhus, tularaemia, rat bite fever, rocky mountain spotted fever and Lassa fever, among others. Only a few species are serious pests or vectors of disease, but it is these rodents that are most closely associated with people.</p>
