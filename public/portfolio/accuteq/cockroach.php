                    <h3>Habitats of Cockroaches</h3>
                    <p>The cockroach prefers a warm, humid, dark environmentand is usually found in tropical or other mild climates. Only a few species have become pests. The cockroach damages more material than it consumes and emits a disagreeable odour. The diet of the roach, which includes both vegetable and animalproducts, ranges from food, paper, clothing, and books to dead insects, especially bed bugs. Strong insecticides are used in cockroach control.</p>

                    <p>Cockroaches are commonly found in buildings and homes because they prefer warm environments, which are close to food and water. Unfortunately, cockroaches can cause allergies and trigger asthma attacks, especially in children. They can also spread nearly 33 different kinds of bacteria in human beings.</p>
                    
                    <h3>Types of Cockroaches as pests</h3>
                    
                    <p>Common types of cockroaches as pests are many. While there are about 69 types of cockroaches commonly found by pest management specialists, the four most common species in the United States are the American, brown-banded, German and Oriental cockroaches.</p>
                    
                    <h3>American Cockroaches</h3>
                    <p>The American cockroach is the largest cockroach found in houses. Despite its name, the American cockroach is not native to North America, but was likely introduced via ships from Africa in the early years of 1600s.</p>

                    <p>Females can hatch up to 150 offspring per year. Cockroaches don’t get their wings until they become adults. Their size is 2 inches and their body shape are oval. They have reddish brown colour, with a yellow band on the head. It has six legs and wings with antenna. American cockroaches will eat just about anything, including plants and other insects. American cockroaches prefer to live in warm, dark, wet areas, like sewers and basements. They often enter structures through drains and pipes.</p>

                    <p>Although American cockroaches can be found in homes, they are also common in larger commercial buildings, such as restaurants, grocery stores and hospitals. Cockroaches crawl through dirty areas and then walk around our homes tracking in lots of bacteria and germs. They can contaminate food by shedding their skins. Their cast-off skin and waste byproducts are allergens that can trigger allergic conditions, such as Asthma, and other illnesses, especially in children.</p>
                    
                    <h3>Brown Banded Cockroaches:</h3>
                    <p>Brown banded cockroaches get their name from the two light bands they have across their dark brownish bodies. The male’s wings are larger than the female’s wings. Brownbanded cockroaches often hide their eggs in or under furniture.</p>

                    <p>They usually live 5-6 ½ months. They are of half an inch in size, with oval body shape. It has brown colour with light bands across the wings. It has six legs, wings and antenna. Brownbanded cockroaches prefer to eat starchy foods, such as wallpaper paste and book bindings. Sometimes they’ll eat non-organic things, like nylon stockings!</p>

                    <p>Brownbanded cockroaches prefer warmer, drier, and higher locations than most cockroaches. While most cockroaches prefer to live in kitchens and pantries, Brownbanded cockroaches will live in any room in the house.</p>

                    <p>They do not need much moisture and avoid light whenever the can. Cockroaches crawl through dirty areas and then walk around our homes tracking in lots of bacteria and germs. They can contaminate food by shedding their skins. Their cast-off skin and waste byproducts are allergens that can trigger allergy and other diseases, especially in children.</p>
                    
                    <h3>German Cockroaches:</h3>
                    <p>German cockroaches can be found all over the world. They are the most common cockroach in the United States. Each German cockroach can live about 100-200 days. These cockroaches are small, about half an inch in size with oval body shape. The colour of body is brown and it has six legs, wings and antenna.

                    <p>Cockroaches are attracted to sweet and floury foods. They also eat non-organic items such as toothpaste and books! German cockroaches live in warm and damp places, like kitchens, bathrooms, and places where people eat and drink.</p>

                    <p>Cockroaches crawl through dirty areas and then walk around our homes tracking in lots of bacteria and germs. They can contaminate food by shedding their skins. Their cast-off skin and waste by products are allergens that can trigger allergy and other diseases, especially in children.</p>
                    
                    <h3>Oriental Cockroaches:</h3>
                    <p>Oriental Cockroaches probably get their names from trade ships but they are actually from Africa. They are large and very dark compared to other cockroaches. They usually travel through sewer pipes and drains. They prefer dirty places and cooler temperatures than other cockroaches. An Oriental cockroach creates a strong smell and is considered one of the dirtiest of all the cockroaches.

                    <p>These cockroaches are one inch in size with oval body shape. It is of dark brown colour and are almost black. It has six legs, and antenna. This cockroach does not have wings and cannot fly. Oriental cockroaches feed on all types of garbage and other organic material. Oriental cockroaches also live in sewers and wet, decaying areas, such as basements and crawlspaces, firewood and piles of leaves.</p>

