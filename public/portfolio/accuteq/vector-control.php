                    <h2>About Vectors and Vector Control</h2>
                    <img src="images/About-Vectors-and-Vector-Control-banner.jpg" alt="About-Vectors-and-Vector-Control-banner">
                    <h3>What is a Vector? </h3>
                    <p>In the science of epidemiology, a disease vector is any agent that carries and transmits aninfectious pathogen into another living organism; most agents regarded, as vectorsare organisms, such as intermediate parasites or microbes, but it could be an inanimate medium of infection such as dust particles etc.</p>
                    
                   <p>Arthropods form a major group of pathogen vectors with mosquitoes, flies, sand flies, lice, fleas, ticks, and mites transmitting a huge number of pathogens. Many such vectors are hematophagous, which feed on blood at some or all stages of their lives. When the insects blood feed, the pathogen enters the blood stream of the host. This can happen in different ways.</p>
                    
                    <p>The Anopheles mosquito, a vector for malaria and filariasis, and various arthropod-borne-virusesinserts its delicate mouthpart under the skin and feeds on its host’s blood. The parasites the mosquito carries are usually located in its salivary glands. Therefore, the parasites are transmitted directly into the host’s blood stream. Pool feeders such as the sand fly and black fly, which are   vectors for pathogens causing serious diseases respectively, will chew a well in the host’s skin, forming a small pool of blood from which they feed.</p>
                    
                    <p>The Triatomine bugs defecate during feeding and the excrement contains the parasites which are accidentally smeared into the open wound by the host responding to pain and irritation from the bite.</p>
                    
                    <h3>What is Vector Control?</h3>
                    <p>Vector control is any method to limit or eradicate the mammals, birds, insects or other arthropods here collectively called “vectors�?, which transmit disease pathogens. The most frequent type of vector control is mosquito control using a variety of strategies.</p>
                    
                    <h3>Principle of Vector Control</h3>
                    <p>Working Principle of Field Oriented Control has the basic theory of the field-oriented control, that consists of controlling the stator currents represented by a vector. This control is based on projections that transform a three-phase time and speed dependent system into a two coordinate, d and q frame, time invariant system.</p>
                  
                    <h3>How does Vector Control work in Pre-Construction sites?</h3>
                    <p>Similar to earth control measures and noise control, contractors are required to submit a plan for their vector control ahead of the construction works which include but are not limited to the following:</p>
                    <p>1. An in-house pest control team to carry out the vector surveillance and control work.</p>
                    <p>2. External Pest Control Operator (PCO) to supplement the in-house vector surveillance and control.</p>
                    <p>3. Source reduction and effective drainage as the main forms of mosquitoes control.</p>
                    <p>4. In-house pest control team shall carry out search and destroy activities of any potential breeding grounds, especially after every rainfall, using the “zoning method�?. This method divides the site into a maximum of seven zones and aims for a more effective vector surveillance and control by focusing on one zone per day.</p>
                    <p>5. Apply larvicides or Anti-Mosquitoes (AM) oil to supplement source reduction.</p>
                    <p>6. Thermal fogging is discouraged and shall only be carried out in accordance with the criteria stated in Code of Practice for Environmental Control Officer.</p>
                    <p>7. Store food in rodent-proof storage containers/cabinets with at least 60cm clearance above ground.</p>
                    <p>8. Remove food waste daily and clean the bins regularly.</p>
                    
                    <h3>How Vector Control is done?</h3>
                    <h5>Vectors can be controlled using various methods.</h5>
                    <p><b>1. Basic sanitation</b></p>
                    <p>This approach targets the elimination or reduction of that part of the environment that facilitates breeding and harbourage (places where vectors find refuge or shelter). It includes the elimination of all possible breeding places for insects, the prevention of stagnation of water to limit the breeding of mosquitoes, and proper solid waste management and use of a latrine to control the breeding of houseflies. The use of clean water from protected sources for drinking prevents the transmission of guinea worm. Rats are controlled by starving them and eliminating their breeding places. Personal hygiene contributes to the control of lice.</p>
                    
                    <p>Generally, a clean home and environment will prevent the breeding of insects. The use of ventilation, latrines and adequate water supply play a significant role in the control of insects.</p>
                    
                    <p><b>2. Physical measures</b></p>
                    <p>These include methods that stop vectors from getting into close contact with humans, and methods that are used to kill vectors. They include bed nets for mosquitoes and wire mesh for flies and mosquitoes Mosquito larvae can be controlled in some water containers by putting a thin layer of used oil on the surface of the water. This acts as a barrier between the water and the air so the larvae cannot access oxygen and suffocate. Physical methods also include traps such as adhesives to control flies and traps for rats and mice. Delousing by boiling or steaming infested clothes are physical methods for controlling lice.</p>
                    <p><b>3. Use of chemicals</b></p>
                    <P>Chemical insecticides can be used for the destruction of adults and larvae of insects. Commonly used chemicals are DDT, malathion and pyrethrums. Pyrethrum-containing aerosols are used for the destruction of cockroaches and flies in our homes. Rodenticides can be used to kill rats and mice. The indiscriminate use of these chemicals, however, could have undesired health effects on users and domestic animals. Extreme care should be taken during the application and storage of chemicals. It is always important to look at the instructions for using the chemical. Environmental health workers and veterinary technicians may be able to assist in the use of chemicals against vectors</P>
                    
                    <p><b>4. Biological methods</b></p>
                    <p>These include several very advanced methods that prevent the successful reproduction of pest species. They include the sterilisation of males ,tsetse fly, mosquito, sex distortion or replacement of genes. All of these methods are expensive and often complex to monitor. Other biological methods involve introducing or encouraging predators of the vector species. For example, small fish can be used to feed on larvae of mosquitoes. Reptiles, birds and frogs feed on adult insects and cats will prey on rats.</p>
                    
                    <p><b>5. Integrated approach</b></p>
                    <p>Integrated vector management includes a combination of two or more of the above methods. This is often more effective than using a single method of control. For example, the rat population may be significantly reduced by combining starving with trapping. Sanitation can be combined with other cheap methods in order to be both sustainable and effective.</p>
                    
                    <h3>How can we prevent Vector borne diseases?</h3>
                    <p>One must avoid contact with blood, secretions, organs or other bodily fluids of infected people or animals. One must make sure that he keeps strict hygiene control of food and avoidunpasteurized dairy products in areas where tick-borne encephalitis can be transmitted.</p>
                    
                    <p>Vector control can be achieved by bird control, mosquito pest control, using mosquito spray, which is a potent and best mosquito killer. Outdoor mosquito repellents also must be used, whereas mosquito spray for home can be used indoors. There are many natural mosquito killers those can be used as mosquito repellents.</p>
                    
                    <p>House fly control measures should also be adopted, as fly spray for house, house fly repellent, house fly killer spray for fly control.</p>
                    
                    
