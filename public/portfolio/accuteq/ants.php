                            <p><b>Ant,</b> from family Formicidae, any of approximately 10,000 species of insects that are social in habit and live together in organized colonies. Ants occur worldwide but are especially common in hot climates. They range in size from about 2 to 25 mm, about 0.08 to 1 inch. Their colour is usually yellow, brown, red, or black. A few genera have a metallic lustre.</p>

                            <h4>Anatomy</h4>
                            
                            <p>Typically, an ant has a large head and a slender, oval abdomen joined to the thorax or midsection, by a small waist. In all ants there are either one or two finlike extensions running across the thin waist region. The antennae are always elbowed. There are two sets of jaws: the outer pair is used for carrying objects such as food and for digging, and the inner pair is used for chewing. Some species have a powerful sting at the tip of the abdomen.</p>
                              
                            <h4>Castes</h4>
                              
                            <p>There are generally three castes or classes, within a colony: queens males, and workers. Some species live in the nests of other species as parasites. In these species the parasite larvae are given food and nourishment by the host workers. Wheeleriella santschii is a parasite in the nests of Monomorium salomonis, the most common ant of northern Africa.</p>
                              
                            <h4>Ants Habitats</h4>
                              
                            <p>Most ants live in nests, which may be located in the ground or under a rock or built above ground and made of twigs, sand, or gravel. Carpenter Ants or Camptonites are large black ants common in North America that live in old logs and timbers. Some species live in trees or in the hollow stems of weeds. Tailor, or weaver, ants, found in the tropics of Africa e.g., Tetramorium, make nests of leaves and similar materials held together with silk secreted by the larvae. Dolichoderus, a genus of ants that are found worldwide, glues together bits of animal faeces for its nest. The widely distributed pharaoh ant or Monomarium pharaonis, a small yellowish insect, builds its nest either in houses, when found in cool climates, or outdoors, when it occurs in warm climates.</p>

                            <p>Army ants, of the subfamily Dorylinae, are nomadic and notorious for the destruction of plant and animal life in their path. The army ants of tropical America for example, travel in columns, eating insects and other invertebrates along the way. Periodically, the colony rests for several days while the queen lays her eggs. As the colony travels, the growing larvae are carried along by the workers. Habits of the African Driver ants are similar.</p>

                            <h4>Ants Social behavior</h4>
                              
                            <p>The social behaviour of the ants, along with that of the honeybees, is the most complex in the insect world. Slave-making ants, of which there are many species, have a variety of methods for “enslaving�? the ants of other species. The queen of Bothriomyrmex decapitans of Africa, for example, allows herself to be dragged by Tapinoma ants into their nest. She then bites off the head of the Tapinoma queen and begins laying her own eggs, which are cared for by the “enslaved�? Tapinoma workers. Workers of the slave-making ant Protomognathus americanus raid nests of Temnothorax ants, stealing the latter’s pupae. The pupae are raised by P. americanus to serve as slaves, and, because the Temnothoraxpupae become imprinted on the chemical odour of the slave-making ants, the captive ants forageand routinely return to the slave-making ant nest.</p>
                            
