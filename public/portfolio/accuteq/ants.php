                             <h4>Argentina Ants:</h4>
                              
                              <p>This species of ant is native to Argentina and Brazil and was probably introduced to the United States in freight ships around the 1890’s. These ants can be found in southern states and in California, Illinois, Maryland, Missouri, Oregon and Washington.</p>

                              <p>These ants are half an inch in size, segmented and oval in shape, dark brown, black in colour. It has six legs, antennas or wings.</p>
                              
                              <p><b>Diet:</b> Argentine ants prefer sweet substances but will eat almost anything including meats, eggs, oils and fats. Also, when foraging for food, Argentine ants leave pheromone trails everywhere they go, instead of just from nest to food source. This habit ensures they do not waste time visiting the same area twice. While in other ant species worker ants are primarily responsible for gather food, Argentine queens also assist with foraging for food.</p>
                              
                              <p><b>Habitat:</b> Argentine ant colonies are located in wet environments near a food source. These colonies can grow to monumental size, sometimes covering entire habitats, such as an entire garden or your whole back yard. Argentine ants do not pose a health threat, but they can contaminate food by leaving their bodily waste behind.</p>
                              
                              <h4>Carpenter Ants:</h4>
                              
                              <p>Carpenter ants get their name because they build their nests in wood. This pest can cause significant damage to your house. There are many types of carpenter ants throughout the U.S. measuring in size from one-quarter inch (about the width of a pencil) for a worker carpenter ant to three-quarters of an inch (about the size of a quarter) for a queen carpenter ant.</p>

                              <p>Each colony is established by a single, fertilized queen. She starts her nest in a cavity in wood, where she raises her first brood of workers. She feeds them saliva and does not leave the nest or feed herself during this time.</p>

                              <p>When they are ready, those workers then get the job of gathering food to feed the next generation. Once mature, this first generation of worker ants work to increase the food supply for the colony. The colony population grows very rapidly. A colony can eventually produce 2,000 or more workers.</p>

                              <p>These ants are half an inch to one in size, segmented and oval in shape, dark brown, black or red in colour. It has six legs, antennas or wings.</p>
                              
                              <p><b>Diet:</b> Carpenter ants do not eat the wood they remove during their nest-building activities, but deposit it outside entrances to the colony in small piles. The diet of carpenter ants includes living and dead insects, meat, fats and sugary foods of all kinds, including honeydew and nectar from plants.</p>
                              
                              <p><b>Habitat:</b> Carpenter ants build nests anywhere they can find water and moldy or damp wood, such as tree stumps, firewood or in the plants around your house. Carpenter ants also build nests inside, usually entering buildings through wet, damaged wood, although it isn’t uncommon for them to adapt to drier environments.</p>
                              
                              <p>Carpenter ants don’t carry disease, but when building a nest inside a home, Carpenter ants dig smooth tunnels inside the wood. These tunnels weaken the wood and potentially damage the wood that keeps the house standing. This kind of damage can be very expensive to fix.</p>
                              
                              <h4>Odorous House Ants:</h4>
                              
                              <p>This ant gets its name from the strong, rotten coconut-like smells it gives off when crushed and the fact that they commonly nest in or around houses. Native to the United States, these ants are very social, living in colonies of up to 100,000 members. These ants are half an inch to one in size, segmented and oval in shape, dark brown, black in colour. It has six legs, antennas or wings.</p>
                              
                              <p><b>Diet:</b> Odorous house ants like to eat dead insects and sugary sweets, especially melon.</p>
                              
                              <p><b>Habitat:</b> Typically living for several years, these ants commonly make their homes in exposed soil, under stones, logs, mulch, debris and other items. They will also nest in wall and floor cracks. Odorous house ants do not pose a health threat, but they can contaminate food by leaving waste behind.</p>
                              
                              <h4>Pavement Ants:</h4>
                              
                              <p>Although these ants can live inside, they get their name because they make their nests in or under cracks in pavement. They are typically found in the eastern half of the United States, California and Washington. Pavement ant colonies average 3,000 to 4,000 members and have several queens. These ants are half an inch to one in size, segmented and oval in shape, dark brown, black in colour. It has six legs, antennas or wings.</p>
                              
                              <p><b>Diet:</b> These ants will eat almost anything, including insects, grease, seeds, honeydew, honey, bread, meats, nuts and cheese.</p>
                              
                              <p><b>Habitat:</b> This ant gets its name because it most commonly nests in soil next to and beneath slabs, sidewalks, patios, and driveways. Indoors, pavement ants nest under a building’s foundation and within hollow foundation walls. Pavement ants do not pose a health threat, but they can contaminate food by leaving waste behind.</p>
                              
                              <h4>Red Imported Fire Ants:</h4>
                              
                              <p>Red imported fire ants are more aggressive than other ant species and have a painful sting. These ants and their tell-tale mound nests should be actively avoided. Red imported fire ants can adapt to many climates and conditions in and around their environment. For example, if the colony senses increased water levels in their nests, they will come together and form a huge ball or raft that is able to float on the water.</p>
                              
                              <p>These ants are half an inch to one in size, segmented and oval in shape, dark reddish brown in colour. It has six legs, antennas or wings.</p>
                              
                              <p><b>Diet:</b> They primarily feed on vegetation.</p>
                              
                              <p><b>Habitat:</b> Red imported fire ants will build their nests in mounds of soil outdoors, in landscape areas or near a building’s foundation. They occasionally enter buildings through holes or cracks in walls and foundations.</p>
                              
                              <p>The sting of a red imported fire ant is painful and often results in a raised welt that becomes a white blister. Persons allergic to insect stings will react more severely. They are frustrating, not only because of the physical pain they can inflict, but because their mound-building activity can damage plant roots and lead to loss of crops.</p>
                              
