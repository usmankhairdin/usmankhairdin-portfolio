                    <h2>House Fly Control</h2>
                    
                    <img src="images/HOUSE-FLY-CONTORL.jpg" alt="HOUSE-FLY-CONTORL">
                    
                    <p>The First step in House fly control is exclusion and sanitation. After these measures, you can use insecticides that come in residual forms, aerosols, fogging materials, and baiting forms. Fly traps have long been a favourite. There are many forms of fly traps, from disposable fly traps to electronic fly light traps with replaceable light bulbs and glue boards.</p>

                    <h3>Exclusion and Sanitation</h3>
                    
                    <p>1. Sanitation is the first measure of defence, even though there are various traps and sprays that are used to kill flies, it is necessary to eliminate the source in order to eliminate them.</p>
                    
                    <p>2. Whenever possible, food and materials on which the flies can lay their eggs must be removed or destroyed, which will isolate the egg-laying adult. Killing adult flies will reduce infestation, but elimination of breeding areas is necessary for good House Fly control management.</p>
                    
                    <p>3. Garbage cans and dumpsters should have tight-fitting lids and be cleaned regularly.</p>
                    
                    <p>4. Drainage will often aid control, getting rid of extra moisture.</p>
                    
                    <p>5. Openings of buildings should be tightly screened with screen.</p>
                    
                    <h3>HOUSE FLY</h3>
                    
                    <p>The housefly, also house-fly or house fly or Musca domestica, is the most common fly occurring in homes and indeed one of the most widely distributed animals and the most familiar of all flies; it is a pest that can facilitate serious diseases.</p>
                    
                    <p>It is the most common fly species found in houses. Adults are grey to black, with four dark, longitudinal lines on the thorax, slightly hairy bodies, and a single pair of membranous wings. They have red eyes, set further apart in the slightly larger female.

                    <p>The female housefly usually mates only once and stores the sperm for later use. She lays batches of about 100 eggs on decaying organic matter such as food waste, carrion or feces These soon hatch into legless, white larvae, maggots. After 2 to 5 days of development, these metamorphose into reddish-brown pupae, about 8 mm (0.3 in) long. Adult flies normally live for 2 to 4 weeks but can hibernate during the winter.</p>

                    <p>The adults feed on a variety of liquid or semiliquid substances, as well as solid materials which have been softened by their saliva.  They can carry pathogens on their bodies and in their feces, contaminate food, and contribute to the transfer of foodborne diseases, while, in numbers, they can be physically annoying. For these reasons, they are considered pests.</p>

                    <p>Houseflies have been used in the laboratory in research into aging and sex determination. Flies appear in literature from Ancient Greek mythology and Aesop’s the Impertinent Insectonwards. Authors sometimes choose the fly to speak of the brevity of life, which deals with mortality subject to uncontrollable circumstances.</p>
                    
                    <h3>Description:</h3>
                    
                    <p>Adult houseflies are usually 6 to 7 mm (0.24 to 0.28 in) long with a wingspan of 13 to 15 mm (0.5 to 0.6 in). The females tend to be larger winged than males, while males have relatively long legs. Females tend to vary more in size and there is geographic variation with larger individuals in higher latitudes. The head is strongly convex in front and flat and slightly conical behind.</p>
                    
                    <p>The pair of large compound eyes, almost touch in the male but are more widely separated in the female. They have three simple eyes and a pair of short antennae. Flies process visual information around seven times more quickly than do humans, enabling them to identify and avoid attempts to catch or swat them, since they effectively see the human’s movements in slow motion with their higher flicker fusion rate.</p>
                    
                    <p>The mouthparts are specially adapted for a liquid diet; the mandibles and maxillae are reduced and not functional, and the other mouthparts form a retractable, flexible proboscis with an enlarged, fleshy tip, the labellum. This is a sponge-like structure that is characterized by many grooves, called pseudotracheae, which suck up fluids by capillary action It is also used to distribute saliva to soften solid foods or collect loose particles.</p>
                    
                    <p>Houseflies have chemoreceptors organs of taste, on the tariff their legs, so they can identify foods such as sugars by walking over them. Flies are often seen cleaning their legs by rubbing them together, enabling the chemoreceptors to taste afresh whatever they walk on next. At the end of each leg is a pair of claws, and below them are two adhesive pads, pull villi, enabling the fly to walk up smooth walls and ceilings.</p>
                    
                    <p>The claws help the fly to unstick the foot for the next step. Flies walk with a common gait on horizontal and vertical surfaces with three legs in contact with the surface and three in movement. On inverted surfaces, they alter the gait to keep four feet stuck to the surface. Flies land on a ceiling by flying straight towards it; just before landing, they make a half roll and point all six legs at the surface, absorbing the shock with the front legs and sticking a moment later with the other four, also.</p>
                    
                    <p>The thorax is a shade of gray, sometimes even black, with four dark, longitudinal bands of even width on the dorsal surface. The whole body is covered with short hairs. Like other Diptera, houseflies have only one pair of wings, what would be the hind pair is reduced to small halteres that aid in flight stability. The wings are translucent with a yellowish tinge at their base. Characteristically, the medial vein (M1+2 or fourth long vein) shows a sharp upward bend.</p>
                    
                    <p>Each wing has a lobe at the back, the calypter, covering the haltere. The abdomen is gray or yellowish with a dark stripe and irregular dark markings at the side. It has 10 segments which bear spiracles for respiration. In males, the ninth segment bears a pair of claspers for copulation, and the 10th bears anal cerci in both sexes.</p>
                    
                    <p>A variety of species around the world appear similar to the housefly, such as the Fannie canicularis; the Stomoxys calcitrans and other members of the Musa genus, the Australian bush fly and several closely related taxa that include M. primitive, M. Shanghainese, M. violacea, and M. varensis. The systematic identification of species may require the use of region-specific taxonomic keys and can require dissections of the male reproductive parts for confirmation.</p>
                    
                    <h3>Diseases:</h3>
                    
                    <p>Houseflies can fly for several miles from their breeding places,carrying a wide variety of organisms on their hairs, mouthparts, vomitus, and faeces. Parasites carried include cysts of protozoa. Houseflies do not serve as a host or act as a reservoir of any bacteria of medical or veterinary importance, but they do serve as mechanical vectors to over 100 pathogens such as those causing typhoid, cholera, tuberculosis and pyogenic cocci, making them especially problematic in hospitals and during outbreaks of certain diseases.</p>
                    
                    <p>Disease-causing organisms on the outer surface of the fly may survive for a few hours, but those in the crop or gut can be viable for several days. Usually, too few bacteria are on the external surface of the flies to cause infection, so the main routes to human infection are through the fly’s regurgitation and defecation.</p>
                    
                    
