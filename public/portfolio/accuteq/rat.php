                    <h2>Rat-Mouse-Mice Control</h2>
                    <img src="images/RATS-MOUSE-PEST-CONTORL-BANNER.jpg" alt="RATS-MOUSE-PEST-CONTORL-BANNER">
                    <h3>The First Step for Rat Control is Sanitation, Inspection and Exclusion</h3>
                    <p>Regular Inspection is an important first step in getting rid of rats. Once you know the location of the rats, you can set traps or place bait.</p>

                    <p>To Exclude is an important rodent control technique. It will get rid of the rats by making it difficult for them to enter the home or structure. Rats are easier to exclude than mice because rats a typically larger. Mice can enter an opening as small as 3/8″ wide. All openings greater that 1/4″ should be sealed to exclude mice. For rats, all openings greater that 1/2″ should be sealed.</p>
                    
                    <p>Rats are wary of new objects, new foods or changed in environment. They are constantly exploring surroundings and notice changes and are suspious by nature. This is why traps and bait stations may be avoided for a day or two. They approach new food or object with caution. Within a rat colony, they may be a few rats that are extra cautious and manage to avoid traps or eating rodent baits.</p>
                    
                    <h3>The Second Step for Rat Control is Trapping or Baiting</h3>
                    <p>The most effective methods to get rid of rats is trapping them and placing rodent baits.</p>
                    
                    <p>Rat, the term generally and indiscriminately applied to numerous members of several rodent families having bodies longer than about 12 cm, or 5 inches. Smaller thin-tailed rodents are just as often indiscriminately referred to as mice. In scientific usage,rat applies to any of 56 thin-tailed, medium-sized rodent species in the genus Rattus native to continental Asia and the adjacent islands of South east Asia, eastward to the Australia-New Guinea region. A few species have spread far beyond their native range in close association with people. The brown rat, also called the Norway rat, and the house rat, also called the black rat, ship rat, or roof rat, live virtually everywhere that human populations have settled; the house rat is predominant in warmer climates, and the brown rat dominates in temperate regions, especially urban areas. Most likely originating in Asia, the brown rat reached Europe in the mid-1500s andNorth America around 1750. The house rat most likely originated in India.</p>
                    
                    <p>Brown and house rats exploit human food resources, eating and contaminating stored grains and killing poultry. They have been responsible for the depletion or extinction of native species of small mammals, birds, and reptiles, especially on oceanic islands. Both the brown and house rat have been implicated in the spread of 40 diseases among humans, including bubonic plague, food poisoning murine typhus tularaemia and leptospirosis. On the other hand, the brown rat has been used in laboratories worldwide for medical, genetic, and basic biological research aimed at maintaining and improving human health. Rats are also kept as pets</p>
                    
                    <h3>Features-</h3>
                    <p>Rats are generally slender with a pointed head, large eyes, and prominent, thinly furred ears. They have moderately long legs and long, sharp claws. The bald soles of their narrow hind feet possess fleshy pads of variable size, depending on species. The brown rat has a larger body than the house rat, and its tail is shorter relative to the body. The brown rat also has thicker fur and 12 pairs of teats instead of 10. Tail length among rats ranges from shorter than body length to appreciably longer. The tail appears smooth and bald but is actually covered with very short, fine hairs. In a very few species, these hairs become longer toward the tip, which gives the tail a slightly tufted appearance. As with any large group of rodents, body size varies within the genus. Most species are about the size of Hoffman’s rat, native to the Indonesian island and weighing 95 to 240 grams (3.4 to 8.5 ounces), with a body length of 17 to 21 cm (6.7 to 8.3 inches) and a tail about as long. One of the smaller species is Osgood’s rat of southern Vietnam, with a body 12 to 17 cm long and a somewhat shorter tail. At the larger extreme is the Sulawesian white-tailed rat measuring 19 to 27 cm long with a tail of 26 to 34 cm.</p>

                    <p>Like Hoffman’s rat, most species have a moderately short, soft, and dense coat. In some species the coat may be thicker and longer, somewhat woolly, or long and coarse; in others, such as the Sulawesian white-tailed ratof India, long and slender guard hairs resembling whiskers extend 4 to 6 cm beyond the coat on the back and rump. Very few Rattus species have spiny fur. Hoffman’s rat also exhibits the basic colour pattern seen in the genus—upperparts of brownish yellow peppered with black to dark brown and speckled with buff and underparts from silvery gray to dark gray, sometimes suffused with buff tones. Tail, ears, and feet are dark brown. As with fur texture, colour is variable. The Sikkim rat has brownish upperparts and a pure white underside; the Himalayan field rat has a brown back, gray underparts, and feet of pearly white. Others have very dark fur, such as the rat native to islands off the west coast of Sumatra. It has brownish black upperparts and a grayish black belly. Although the tail is uniformly gray to dark brown in most rats ,sometimes nearly black,  a few species show one of two bicoloured patterns: brown on the tail’s entire upper surface with a paler tone or pure white on the undersurface, as in the Himalayan field rat and the Turkestan rat or brown all around the basal third to half of the tail with the rest uniformly white, as in Hoogerwer rat and the white-tailed rat of Sulawesi.</p>

                   <h3>Natural Habitat-</h3>
                    <p>In their natural habitats rats are primarily nocturnal—the brown rat is a prominent exception, being active day and night in both urban and rural environments. All rats are terrestrial, and many are also arboreal. The Sulawesian white-tailed rat is an excellent climber and exhibits the classic combination of arboreal traits within rats, a very long tail relative to body length, extremely long guard hairs over the back and rump, and wide hind feet with prominent, fleshy footpads. This rodent den among the roots of large trees and forages high in the crowns of understory and canopy trees. By contrast, those species having a tail considerably shorter than body length, short guard hairs over the back and rump, and inconspicuous pads on the soles of their hind feet tend to be primarily ground-dwelling. Most rats can swim; species with thick and somewhat woolly fur generally swim well, and some are adept swimmers that forage in aquatic environments. The brown rat, for example, has a terrestrial rat’s characteristic morphology and is a comparatively poor climber, but it has dense fur and readily enters lakes and streams and sewers to hunt for fish, invertebrates, or other food. The house rat, on the other hand, is extremely agile above the ground, being able to climb and run along narrow branches and wires.</p>
                    
                    <p>Rats are thought to eat everything, a conception that comes from familiarity with the highly adaptable brown rat and house rat, but diet actually differs according to species and habitat. Where it lives with humans, the house rat does consume nearly anything digestible, especially stored grains. The brown rat is basically omnivorous but prefers a carnivorous diet, aggressively pursuing a wide variety of prey including shrimp, snails, mussels, insects, bird eggs and young, amphibians, eels, fish, pheasant, pigeons, poultry, rabbits, and carrion. Many rainforest species, including the Sulawesian white-tailed rat and Hoffman’s rat, eat only fruit and the seeds within, but some, such as the Philippine forest rat, also eat insects and worms. Other tropical species, such as the rice-field rat and Malayan field rat, primarily consume the insects, snails, slugs, and other invertebrates found in habitats of forest patches, secondary growth, scrubby and fallow fields, palm plantations, and rice fields</p>
                    
                    <p>Some rats excavate burrows or build their nests beneath boulders, rotting tree trunks, or other kinds of shelter on the forest floor; they may also shelter in deep rock crevices or caves and in dwellings from small village huts to large city buildings. Rat reproduction has been most intensively studied in the brown rat. This prolific rodent reaches sexual maturity at three months and may produce up to 12 litters of 2 to 22 young (8 or 9 is usual) per year, with peaks in the spring and autumn and a gestation period of 21 to 26 days. Breeding occurs throughout the year in many tropical species but in others may be restricted to wet seasons or summer months. Litter sizes in tropical forest species tend to be much smaller (one to six), and seasonal breeders, particularly in Australian habitats, produce significantly fewer annual litters.</p>
                    
                    <h3>Classification-</h3>
                    <p>Members of the genus ratsare native to temperate and tropical continental Asia, the Australia–New Guinea region, and islands between those landmasses. Five clusters of species within the genus are recognized by some authorities.</p>
                    
                    <p>The norvegicus group, consisting only of the brown rat, may have originated in northern or northeastern China</p>
                    
                    <p>Most of the 20 species in the ratgroup are specialto subtropical and tropical Asia from peninsular India to southeastern China, Southeast Asia, Taiwan, some islands in the Philippines, and Sulawesi. They live in lowland and montane rainforests, scrublands, agricultural and fallow fields, and human structures. In addition to the house rat, the distributions of four other species extend outside continental Southeast Asia, beyond to some Pacific islands, and most likely represent introductions caused by human activities</p>
                    
