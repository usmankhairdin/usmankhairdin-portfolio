                    <h3>Mosquito Control- the way to prevent many epidemics.</h3>
                    <h3>The health dangers spread by mosquitoes-</h3>
                    <p>India is experiencing major health threats every year from mosquito borne diseases, in this country. While the dengue outbreak in Delhi has hit the national headlines, little attention has been given to equally worrying data from states such as Karnataka, Kerala and Tamil Nadu, which between them account for almost half of India’s 22,079 dengue cases till September 13, the last day till when country-wide data is available.</p>

                    <p>Mosquito-borne diseases including chikungunya, dengue, malaria and Japanese encephalitis cases has been on the rise across the country, with chikungunya recording 300%, the highest, increase in cases between 2012-2015.Meanwhile, dengue cases increased 157%, followed by Japanese encephalitis cases clocking 124% rise, according to National Health Profile 2017 report.</p>
                    
                    <p>Chikungunya cases showed a declining trend until 2012, when it recorded the lowest number of cases that is 15,977. Thereafter, the numbers surged drastically to 58,264, according to the 2016 (provisional) data.With death toll rising following the rapid spread of mosquito-borne diseases in the country, India’s success in achieving its target to eliminate these diseases seems unclear.</p>
                    
                    <h3>Mosquito Control- the need of the hour</h3>
                    <p>Mosquito control manages the population of mosquitoes to reduce their damage to human health, economies, and enjoyment. Mosquito control is a vital public-health practice throughout the world and especially in the tropics because mosquitoes spread many diseases, such as malaria and Zika virus.</p>
                    
                    <h3>Mosquito Control operations are targeted against three different problems:</h3>
                    <p>1. Nuisance mosquitoesbother people around homes or in parks and recreational areas.</p>

                    <p>2. Economically important mosquitoesreduce real estate values, adversely affect tourism and related business interests, or negatively impact livestock or poultry production.</p>

                    <p>3. Public healthis the focus when mosquitoes are vectors, or transmitters, of infectious diseases</p>
                    
                    <h3>Measures to Mosquito Control-</h3>
                    <ul>
                        <li>Monitoring the population of mosquito in a defined area and keeping them from growing.</li>
                        <li>Reduction the breeding and growing sources of mosquitoes, such as emptying the standing water in the area.</li>
                        <li>Biological Control of mosquitoes breeding and growing by introducing Gambusia fishes in the ponds of stranded water, who eat the mosquito larvae. It also introduces infection through pathogensto target mosquitoes to kill them.</li>
                        <li>Adoption of experimental biological control methods to mosquito killing by introducing large number of sterile males to the area.</li>
                        <li>Larva of mosquitoes can be trapped by providing artificial breeding grounds to them.</li>
                        <li>The adult mosquitoes can be trapped by genetic engineering.</li>
                        <li>Addition of oil drips in water is an eco-friendly way of mosquito control.</li>
                        <li>Larvae of mosquito can be killed by exposing the larvae to contact poison, the mosquito insecticides.</li>
                        <li>Adult mosquitoes can be controlled by mosquito pest control on both ground level or aerial level.</li>
                    </ul>
                    
                    <h3>The common mosquito insecticides-</h3>
                    <p>The common mosquito insecticides are-</p>
                    
                        <p>1. D.T.T.</p>
                        <p>2. Lindane</p>
                        <p>3. Malathion</p>
                        <p>4. Propoxur</p>
                    
                    <h3>Role of Pest Control in Mosquito Control-</h3>
                    <p>The role of a good pest control service to control mosquitoes in either a residential or a commercial area is very much beyond any doubt. Mosquitoes are infamous for spreading extremely dangerous diseases such as malaria, dengue, brain fever, cerebral malaria and filariasis. Having a mosquito infestation in close proximity to a person and his family is an extremely dangerous situation and can be fatal. The primary goal is to keep homes and families safe from mosquitoes.</p>
                    
