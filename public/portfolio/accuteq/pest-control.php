                    <li>Damage buildings. For example, termites can cause considerable damage to timber in buildings.</li>
                    <li>Bite people. For example, bed bugs (so called because they often bite people in their beds) are very difficult and expensive to control. Their bites can cause great irritation to those bitten and, like mosquito bites, can become infected if scratched.</li>
